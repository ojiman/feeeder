                     Feed(title: "テクノロジー", symbol: "cpu"),
                     Feed(title: "週末の読み物", symbol: "leaf")]
        feeds.forEach { context.insert($0) }
        let entries: [(Int, String, String, String)] = [
            (0, "読むことに、集中できる場所を。", "たくさん集めるよりも、大切な記事をゆっくり読む。小さなRSSリーダーの最初の一歩です。", """
